import { type getProductForEdit } from "./queries";
import { type ProductFormInput } from "./schema";

export const emptyProductForm: ProductFormInput = {
  name: "",
  slug: "",
  sku: "",
  categoryId: "",
  productType: "",
  shortDescription: "",
  description: "",
  material: "",
  materials: "",
  colors: "",
  dimensions: "",
  weight: "",
  originCountry: "BD",
  originRegion: "",
  minimumOrderQuantity: "",
  unit: "pieces",
  priceMin: "",
  priceMax: "",
  currency: "USD",
  incoterm: "FOB",
  leadTimeDays: "",
  productionCapacity: "",
  packagingDetails: "",
  hsCode: "",
  sampleAvailable: false,
  isCustomizable: false,
  customizationOptions: "",
  retailPrice: "",
  stockQuantity: "",
  alibabaUrl: "",
  alibabaProductId: "",
  isActive: false,
  isFeatured: false,
  seoTitle: "",
  seoDescription: "",
  images: [],
  variants: [],
};

type Editable = NonNullable<Awaited<ReturnType<typeof getProductForEdit>>>;

export function productToForm(p: Editable): ProductFormInput {
  const s = (v: string | null | undefined) => v ?? "";
  const n = (v: number | null | undefined) =>
    v === null || v === undefined ? "" : String(v);
  return {
    name: p.name,
    slug: p.slug,
    sku: s(p.sku),
    categoryId: p.categoryId,
    productType: s(p.productType),
    shortDescription: s(p.shortDescription),
    description: s(p.description),
    material: s(p.material),
    materials: p.materials.join(", "),
    colors: p.colors.join(", "),
    dimensions: s(p.dimensions),
    weight: s(p.weight),
    originCountry: p.originCountry,
    originRegion: s(p.originRegion),
    minimumOrderQuantity: n(p.minimumOrderQuantity),
    unit: p.unit,
    priceMin: p.priceMin?.toString() ?? "",
    priceMax: p.priceMax?.toString() ?? "",
    currency: p.currency,
    incoterm: p.incoterm ?? "",
    leadTimeDays: n(p.leadTimeDays),
    productionCapacity: s(p.productionCapacity),
    packagingDetails: s(p.packagingDetails),
    hsCode: s(p.hsCode),
    sampleAvailable: p.sampleAvailable,
    isCustomizable: p.isCustomizable,
    customizationOptions: p.customizationOptions.join("\n"),
    retailPrice: p.retailPrice?.toString() ?? "",
    stockQuantity: n(p.stockQuantity),
    alibabaUrl: s(p.alibabaUrl),
    alibabaProductId: s(p.alibabaProductId),
    isActive: p.isActive,
    isFeatured: p.isFeatured,
    seoTitle: s(p.seoTitle),
    seoDescription: s(p.seoDescription),
    images: p.images.map((i) => ({
      imageUrl: i.imageUrl,
      publicId: i.publicId,
      altText: i.altText,
      width: i.width,
      height: i.height,
    })),
    variants: p.variants.map((v) => ({
      id: v.id,
      name: v.name,
      sku: s(v.sku),
      color: s(v.color),
      size: s(v.size),
      material: s(v.material),
      isActive: v.isActive,
    })),
  };
}
